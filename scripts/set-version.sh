#!/usr/bin/env bash
# Overwrites version.lua with the value of the GAME_VERSION environment variable
# (typically the git tag for a tagged CI build).  If GAME_VERSION is unset or
# empty, the script leaves the checked-in fallback ("dev") in place.
#
# Usage:
#   GAME_VERSION=v1.0.0 scripts/set-version.sh
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FILE="$ROOT_DIR/version.lua"

VERSION="${GAME_VERSION:-}"
if [[ -z "$VERSION" ]]; then
    echo "set-version: GAME_VERSION not set; keeping existing version.lua" >&2
    exit 0
fi

# Escape embedded double-quotes and backslashes for safe Lua string literal.
ESCAPED=$(printf '%s' "$VERSION" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

cat > "$OUT_FILE" <<EOF
-- Generated by scripts/set-version.sh during CI build.
-- Do not edit by hand; runtime fallback for local builds is 'dev'.
return "$ESCAPED"
EOF

echo "set-version: wrote version.lua = \"$ESCAPED\""
